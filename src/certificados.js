let RAIZES = RAIZES_PEM.map(p => new X509Certificate(p));

function _cadeia(certificate) {
  const lista = [];
  const vistos = new Set();
  let c = certificate;
  while (c && c.data && lista.length < 8) {
    const x = new X509Certificate(c.data);
    if (vistos.has(x.fingerprint256)) break;
    vistos.add(x.fingerprint256);
    lista.push(x);
    c = c.issuerCert;
  }
  return lista;
}

function _valido(x, agora) {
  return new Date(x.validFrom) <= agora && agora <= new Date(x.validTo);
}

function _assinadoPor(x, emissor) {
  try { return !!x.checkIssued(emissor) && x.verify(emissor.publicKey); } catch { return false; }
}

// true só se o certificado do site (url) tem uma cadeia válida que termina
// numa das raízes embutidas.
function confiarNaCadeia(url, certificate) {
  const host = new URL(url).hostname;
  const lista = _cadeia(certificate);
  if (!lista.length) return false;
  const agora = new Date();
  if (!lista[0].checkHost(host)) return false;
  for (let i = 0; i < lista.length; i++) {
    const x = lista[i];
    if (RAIZES.some(r => r.fingerprint256 === x.fingerprint256)) return i > 0 && _valido(x, agora);
    if (!_valido(x, agora)) return false;
    const raiz = RAIZES.find(r => _assinadoPor(x, r));
    if (raiz) return _valido(raiz, agora);
    const prox = lista[i + 1];
    if (!prox || !prox.ca || !_assinadoPor(x, prox)) return false;
  }
  return false;
}

